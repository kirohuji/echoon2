// ─── 主函数 ───
async function main() {
  console.log('🗂️  开始填充资料库：全国导游资格外语面试考纲...');

  // 清空资料库表（避免重复插入）
  // 先解除所有父子引用关系（自引用 FK 约束），再清空
  await prisma.resourceNode.updateMany({ data: { parentId: null } });
  await prisma.resourceNode.deleteMany();
  console.log('  ✓ 已清空现有资料库数据');

  // ─── 根节点 ───
  const root = await prisma.resourceNode.create({
    data: {
      name: '全国导游资格外语面试考纲资料库',
      type: 'folder',
      region: null,
      description: '基于《全国导游资格考试现场考试大纲》整理的外语类考纲资料库，涵盖全国31个省市自治区的面试要求、考试类别、评分标准和考点信息。按分类和地区两个维度组织，支持快速检索。',
      sortOrder: 0,
    },
  });
  console.log('  ✓ 根目录已创建');

  // ─── 01-全国通用要求 ───
  const reqFolder = await prisma.resourceNode.create({
    data: {
      parentId: root.id,
      name: '01-全国通用要求',
      type: 'folder',
      description: '全国外语类现场考试的通用要求，适用于所有地区。',
      sortOrder: 1,
    },
  });

  for (let i = 0; i < nationalRequirements.length; i++) {
    const item = nationalRequirements[i];
    await prisma.resourceNode.create({
      data: {
        parentId: reqFolder.id,
        name: item.name,
        type: 'document',
        description: item.description,
        sortOrder: i + 1,
      },
    });
  }
  console.log(`  ✓ 全国通用要求（${nationalRequirements.length}项）已创建`);

  // ─── 02-各省考纲速览 ───
  const overviewFolder = await prisma.resourceNode.create({
    data: {
      parentId: root.id,
      name: '02-各省考纲速览',
      type: 'folder',
      description: '各省份外语面试考试概览，包含考试类别、考试时间、分值比例等关键信息。',
      sortOrder: 2,
    },
  });

  for (let i = 0; i < regionOverviews.length; i++) {
    const r = regionOverviews[i];
    let description = `**页码范围**：${r.page}\n\n**主要类别**：${r.categories || '（参见分类考纲详情）'}\n\n**考试要求**：${r.excerpt}`;
    if (r.timeInfo) description += `\n\n**考试时间**：${r.timeInfo}`;
    if (r.scoreInfo) description += `\n\n**分值信息**：${r.scoreInfo}`;

    await prisma.resourceNode.create({
      data: {
        parentId: overviewFolder.id,
        name: `${r.region}考纲概览`,
        type: 'document',
        region: r.region,
        description,
        sortOrder: i + 1,
      },
    });
  }
  console.log(`  ✓ 各省考纲速览（${regionOverviews.length}条）已创建`);

  // ─── 03-分类考纲详情 ───
  const detailFolder = await prisma.resourceNode.create({
    data: {
      parentId: root.id,
      name: '03-分类考纲详情',
      type: 'folder',
      description: '按考试类别分组的详细考纲内容，每个类别下按省份列出具体要求。适合针对性复习。',
      sortOrder: 3,
    },
  });

  // 为每个类别创建文件夹，然后填充各地区的详细内容
  let totalDocs = 0;
  for (const catDef of categoryDefinitions) {
    // 筛选出该类别下所有地区的记录
    const items = categoryDetails.filter((d) => d.category === catDef.code);
    if (items.length === 0) continue;

    const catFolder = await prisma.resourceNode.create({
      data: {
        parentId: detailFolder.id,
        name: catDef.name,
        type: 'folder',
        description: `${catDef.name}类考纲要求，共涵盖${items.length}个地区。`,
        sortOrder: catDef.sortOrder,
      },
    });

    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      await prisma.resourceNode.create({
        data: {
          parentId: catFolder.id,
          name: `${item.region}-${item.title}`,
          type: 'document',
          region: item.region,
          description: `**适用范围**：${item.scope}\n\n${item.content}`,
          sortOrder: i + 1,
        },
      });
      totalDocs++;
    }
  }
  console.log(`  ✓ 分类考纲详情（${totalDocs}条文档，${categoryDefinitions.filter(c => categoryDetails.some(d => d.category === c.code)).length}个类别）已创建`);

  // ─── 统计 ───
  const totalNodes = await prisma.resourceNode.count();
  console.log(`\n🎉 资料库填充完成！共创建 ${totalNodes} 条资源节点。`);
  console.log(`   目录结构：根目录 → 3个子目录 → ${categoryDefinitions.filter(c => categoryDetails.some(d => d.category === c.code)).length}个分类目录 → 文档`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
